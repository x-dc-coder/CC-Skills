def sha256_bytes(data: bytes) -> str:
    digest = hashlib.sha256()
    digest.update(data)
    return digest.hexdigest()


def _source_text(blocks: list[dict[str, JsonValue]]) -> str:
    """Every field doc_model treats as prose-ish text, joined for language stats."""
    parts: list[str] = []
    for block in blocks:
        for key in ("text", "table_body"):
            value = block.get(key)
            if isinstance(value, str):
                parts.append(value)
        items = block.get("list_items")
        if isinstance(items, list):
            parts.extend(str(item) for item in items if isinstance(item, str))
        for key, value in block.items():
            if key.endswith("_caption") and isinstance(value, list):
                parts.extend(str(item) for item in value if isinstance(item, str))
    return "\n".join(parts)


def build_meta(*, blocks: list[dict[str, JsonValue]], source_name: str,
               source_sha256: str, source_format: str) -> dict[str, JsonValue]:
    """_META.json for an imported document.

    Mirrors paper-reader key set so downstream consumers need no second schema,
    and fills every engine field with null - no engine ran.  Language uses
    text_metrics.detect_language, the identical rule paper-reader and the metrics
    layer share, so the cross-layer check stays meaningful.
    """
    import text_metrics

    language = text_metrics.detect_language(_source_text(blocks))
    return {
        "engines": "import",
        "marker": {"ok": False},
        "mineru": {"ok": False},
        "pdf_sha256": None,
        "pdf_sha256_note": "imported from " + source_format + "; source is not a PDF",
        "engine_versions": {
            "marker": None, "mineru": None, "surya": None,
            "torch": None, "cuda": None, "python": None,
        },
        "engine_versions_source": "not_applicable",
        "engine_versions_note": "no conversion engine ran; source was imported",
        "language": language["language"],
        "cjk_ratio": language["cjk_ratio"],
        "lang_source": "import_source_text",
        "import_provenance": {
            "importer_version": IMPORTER_VERSION,
            "source_format": source_format,
            "source_name": source_name,
            "source_sha256": source_sha256,
        },
    }


def write_paper(*, out_dir: Path, paper_id: str, blocks: list[dict[str, JsonValue]],
                meta: dict[str, JsonValue]) -> Path:
    """Write one canonical paper directory in paper-reader's layout.

    Sorting the JSON keys makes the output byte-stable across Python versions;
    block order is document order and must not be sorted.
    """
    paper_dir = out_dir / paper_id
    content_dir = paper_dir / "mineru" / paper_id / "auto"
    content_dir.mkdir(parents=True, exist_ok=True)
    content_path = content_dir / (paper_id + "_content_list.json")
    payload = json.dumps(blocks, ensure_ascii=False, indent=2, sort_keys=True)
    content_path.write_text(payload + "\n", encoding="utf-8")
    meta_path = paper_dir / "_META.json"
    meta_path.write_text(
        json.dumps(meta, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8")
    return paper_dir


def _load_blocks(path: Path, source_format: str,
                 slim: bool) -> list[dict[str, JsonValue]]:
    if source_format == "markdown":
        return markdown_to_blocks(path.read_text(encoding="utf-8"), slim=slim)
    if source_format == "docx":
        return docx_to_blocks(path, slim=slim)
    if source_format == "text":
        return plain_text_to_blocks(path.read_text(encoding="utf-8"))
    raise CanonicalImportError(path, "unsupported format " + repr(source_format))


_EXTENSIONS: Final = {".md": "markdown", ".markdown": "markdown",
                      ".txt": "text", ".docx": "docx"}


def import_file(source: Path, out_dir: Path, *, paper_id: str | None = None,
                source_format: str | None = None, slim: bool = False) -> Path:
    """Import one source file into a canonical paper directory."""
    if not source.is_file():
        raise CanonicalImportError(source, "source file not found")
    if source_format is None:
        source_format = _EXTENSIONS.get(source.suffix.lower(), "")
        if not source_format:
            raise CanonicalImportError(
                source, "unknown extension " + repr(source.suffix) + "; pass --format")
    paper_id = paper_id or source.stem
    blocks = _load_blocks(source, source_format, slim)
    if not blocks:
        raise CanonicalImportError(source, "no blocks produced; source is empty")
    meta = build_meta(blocks=blocks, source_name=source.name,
                      source_sha256=sha256_bytes(source.read_bytes()),
                      source_format=source_format)
    return write_paper(out_dir=out_dir, paper_id=paper_id, blocks=blocks, meta=meta)


def import_corpus(source_dir: Path, out_dir: Path,
                  *, slim: bool = False) -> list[Path]:
    """Import every recognised file in a directory as one paper each."""
    imported: list[Path] = []
    for path in sorted((p for p in source_dir.iterdir() if p.is_file()),
                       key=lambda p: p.name):
        if path.suffix.lower() not in _EXTENSIONS:
            continue
        imported.append(import_file(path, out_dir, slim=slim))
    if not imported:
        raise CanonicalImportError(source_dir, "no .md/.txt/.docx files found")
    return imported


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Import Markdown/docx/plain text into the canonical "
                    "content_list.json layout paper-metrics reads.")
    parser.add_argument("--source", required=True,
                        help="source file, or a directory of source files")
    parser.add_argument("--out", required=True, help="output corpus directory")
    parser.add_argument("--format", choices=["markdown", "docx", "text"], default=None,
                        help="force a format; otherwise inferred from the extension")
    parser.add_argument("--id", default=None, help="paper id (defaults to file stem)")
    parser.add_argument("--slim", action="store_true",
                        help="drop image blocks (fixture mode; S-SIZ-04 reads nothing)")
    args = parser.parse_args(argv)

    source = Path(args.source)
    out_dir = Path(args.out)
    try:
        if source.is_dir():
            paths = import_corpus(source, out_dir, slim=args.slim)
        else:
            paths = [import_file(source, out_dir, paper_id=args.id,
                                 source_format=args.format, slim=args.slim)]
    except CanonicalImportError as exc:
        print("[canonical_import] ERROR: " + str(exc), file=sys.stderr)
        return 2
    for path in paths:
        print("[canonical_import] " + str(source) + " -> " + str(path))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
